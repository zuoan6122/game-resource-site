# 为所有 key 自动补充简体别名（opencc 繁体→简体），避免繁体键在归一化后失配
_cc = opencc.OpenCC('t2s')
for _k, _v in list(TRANSLATION_MAP.items()):
    _s = _cc.convert(_k)
    if _s != _k:
        TRANSLATION_MAP.setdefault(_s, _v)

# 编译最长优先的正则（key 按长度降序）
_TRANSLATION_RE = re.compile(
    '|'.join(map(re.escape, sorted(TRANSLATION_MAP, key=len, reverse=True)))
)
# 仅含英文字母的 key 的正则（第一轮只替换英文短语，避免中文短 key 抢先替换破坏长 key）
_EN_KEYS = [k for k in TRANSLATION_MAP if re.search(r'[a-z]', k)]
_TRANSLATION_RE_EN = re.compile(
    '|'.join(map(re.escape, sorted(_EN_KEYS, key=len, reverse=True)))
)


def apply_translation(s, english_only=False):
    """将标题中的译名变体统一替换为规范 token。
    english_only=True 时只替换含英文字母的 key（用于去符号前，保护中文长 key）。"""
    if english_only:
        return _TRANSLATION_RE_EN.sub(lambda m: TRANSLATION_MAP[m.group(0)], s)
    return _TRANSLATION_RE.sub(lambda m: TRANSLATION_MAP[m.group(0)], s)
